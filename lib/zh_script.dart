const chineseScriptModes = {
  'traditional': '繁體中文',
  'simplified': '简体中文',
};

class ChineseScript {
  static String _mode = 'traditional';

  static String get mode => _mode;

  static bool get isTraditional => _mode == 'traditional';

  static set mode(String value) {
    _mode = value == 'simplified' ? 'simplified' : 'traditional';
  }
}

/// Converts Simplified Chinese UI strings to Traditional Chinese when
/// [ChineseScript.isTraditional] is enabled.
String zh(String text) {
  if (!ChineseScript.isTraditional || text.isEmpty) return text;
  var result = text;
  for (final entry in _phrases) {
    if (result.contains(entry.$1)) {
      result = result.replaceAll(entry.$1, entry.$2);
    }
  }
  final buffer = StringBuffer();
  for (var i = 0; i < result.length; i++) {
    final ch = result[i];
    buffer.write(_charMap[ch] ?? ch);
  }
  return buffer.toString();
}

